"""/describe: a PR summary, change type and per-file walkthrough.

Published into the PR body between PRGuard's markers (the author's own text is
kept untouched), or as a persistent comment, as `.prguard.toml` says.
"""

from __future__ import annotations

import re
from typing import Any

from backend import context as ctxmod
from backend.agents import llm, prompts
from backend.agents.specialists import extract_json
from backend.config import settings
from backend.gateway.base import ToolGateway
from backend.models import Denial, Description, TaskContext, UpstreamError

AGENT_ID = "prguard-describer"
START, END = "<!-- prguard:describe:start -->", "<!-- prguard:describe:end -->"
_SECTION = re.compile(re.escape(START) + r".*?" + re.escape(END), re.DOTALL)


def strip_section(body: str) -> str:
    return _SECTION.sub("", body or "").rstrip()


def parse(text: str) -> Description | None:
    data = extract_json(text)
    if not isinstance(data, dict):
        return None
    walkthrough = []
    for item in data.get("walkthrough") or []:
        if isinstance(item, dict) and (item.get("file") or item.get("path")):
            walkthrough.append({"file": str(item.get("file") or item.get("path"))[:200],
                                "change": str(item.get("change") or item.get("description") or "")[:300]})
    change_type = data.get("change_type") or data.get("type") or []
    if isinstance(change_type, str):
        change_type = [change_type]
    return Description(title=str(data.get("title") or "")[:120], change_type=[str(t)[:30] for t in change_type][:4],
                       summary=str(data.get("summary") or "")[:1500], walkthrough=walkthrough[:60],
                       risks=str(data.get("risks") or "")[:500])


def mock(context: dict[str, Any]) -> Description:
    files = context.get("files", [])
    return Description(
        title=context.get("title", ""), change_type=["feature" if any(f.get("status") == "added" for f in files) else "refactor"],
        summary=f"[MOCK LLM] Changes {len(files)} file(s): " + ", ".join(f["filename"] for f in files[:8]),
        walkthrough=[{"file": f["filename"], "change": f"{f.get('status', 'modified')}, "
                      f"+{f.get('additions', f.get('patch', '').count(chr(10) + '+'))} lines"} for f in files[:30]],
        risks="",
    )


def markdown(d: Description, head_sha: str, model: str) -> str:
    lines = ["### 🛡️ PRGuard description", ""]
    if d.change_type:
        lines.append(f"**Type:** {', '.join(d.change_type)}")
    if d.summary:
        lines += ["", d.summary]
    if d.walkthrough:
        lines += ["", f"<details><summary><b>Walkthrough</b> ({len(d.walkthrough)} file{'s' if len(d.walkthrough) != 1 else ''})</summary>",
                  "", "| File | Change |", "|---|---|"]
        lines += [f"| `{w['file']}` | {w['change'].replace('|', '/')} |" for w in d.walkthrough]
        lines += ["", "</details>"]
    if d.risks:
        lines += ["", f"**Reviewer focus:** {d.risks}"]
    if d.title:
        lines += ["", f"<sub>Suggested title: {d.title}</sub>"]
    lines.append(f"<sub>Generated by PRGuard ({model}) for `{head_sha[:7]}`. Edit freely outside this section.</sub>")
    return "\n".join(lines)


async def run(ctx: TaskContext, context: dict[str, Any], options: ctxmod.Options,
              gateway: ToolGateway) -> tuple[Description, list[str], dict[str, Any]]:
    cfg = context["config"]
    usage: dict[str, Any] = {}
    if settings.llm_is_mock:
        description, model = mock(context), "MOCK LLM"
    else:
        result = await llm.chat(prompts.describe_system(cfg.describe.extra_instructions), ctxmod.pr_prompt(context))
        usage, model = result.usage(), result.model or settings.llm_model
        description = parse(result.text)
        if description is None:
            raise llm.LLMError(f"model returned no usable description: {result.text[:200]!r}")

    posted: list[str] = []
    if options.publish:
        section = markdown(description, ctx.head_sha, model)
        try:
            if cfg.describe.publish == "body":
                author = strip_section(context.get("body", ""))
                body = f"{author}\n\n{START}\n{section}\n{END}" if author else f"{START}\n{section}\n{END}"
                res = await gateway.call(AGENT_ID, ctx, "update_pull_request_body",
                                         {"repo": ctx.repo_full_name, "pull_number": ctx.pr_number, "body": body})
            else:
                res = await gateway.call(AGENT_ID, ctx, "upsert_issue_comment",
                                         {"repo": ctx.repo_full_name, "pull_number": ctx.pr_number, "marker": "describe",
                                          "body": section})
            if not isinstance(res, Denial) and isinstance(res.data, dict) and res.data.get("html_url"):
                posted.append(res.data["html_url"])
        except UpstreamError:
            pass
    return description, posted, usage
